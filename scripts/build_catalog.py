"""Regenerate the file catalog: catalog/CATALOG.csv, catalog/README.md, catalog/COUNTRIES.md.

Every file gets labels inferred from where it lives (kind / semester / country /
status). Re-run after adding or moving files:

    python3 scripts/build_catalog.py
"""
import csv
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CAT = ROOT / "catalog"
SKIP_TOP = {".git", "catalog", ".claude", "scripts", ".github"}
SEM_RE = re.compile(r"^(\d{4}-(spring|fall)|\d{4}-\d{4}|\d{4}|archive-2013-2018)$")

COUNTRIES = sorted({
    *"Argentina Australia Austria Belgium Benin Bolivia Brazil Canada Chile China Colombia Denmark Ecuador Egypt Estonia Ethiopia Finland France Germany Ghana Greece Guatemala Iceland India Indonesia Ireland Israel Italy Japan Kenya Kuwait Lebanon Libya Malaysia Mauritania Mexico Morocco Myanmar Netherlands Nicaragua Niger Nigeria Norway Pakistan Panama Paraguay Peru Philippines Poland Portugal Qatar Russia Senegal Singapore Spain Sweden Switzerland Thailand Togo Tunisia Turkey Ukraine Uruguay Vietnam Zimbabwe".split(),
    "Saudi Arabia", "South Africa", "United Kingdom", "United Arab Emirates", "New Zealand", "Sri Lanka",
    "Burkina Faso", "Lao PDR", "Viet Nam", "Costa Rica", "Timor-Leste", "The Gambia", "USMCA",
}, key=len, reverse=True)
ALIASES = {"Viet Nam": "Vietnam", "Lao PDR": "Laos"}


def labels(rel: Path):
    p = rel.parts
    top = p[0]
    sem = next((x for x in p if SEM_RE.match(x)), "")
    kind = {
        "reports": "country-report", "code": "code", "data": "data", "templates": "template",
        "presentations": "presentation", "literature": "literature-review", "admin": "admin",
        "docs": "docs",
    }.get(top, "other")
    if top == "code" and len(p) > 1:
        kind = {"current": "analysis-notebook", "data-retrieval": "data-pipeline",
                "report-automation": "report-automation"}.get(p[1], "analysis-notebook")
    if top == "data" and len(p) > 1:
        kind = {"raw": "raw-comtrade", "cleaned": "cleaned-exports", "results": "model-output",
                "archive": "dataset-snapshot"}.get(p[1], "data")
        if rel.name.startswith("GDP_"):
            kind = "gdp"
    status = "archive"
    s = str(rel)
    if "DO NOT USE" in s:
        status = "do-not-use"
    elif top in ("docs", "literature", "templates") and "archive" not in p:
        status = "current"
    elif p[:2] in (("code", "current"), ("code", "data-retrieval"), ("code", "report-automation"),
                   ("data", "raw"), ("data", "cleaned")):
        status = "current"
    elif top == "presentations" and "archive" not in p:
        status = "current"
    elif top == "reports" and sem == latest_report_semester():
        status = "latest"
    country = ""
    low = s.lower()
    for c in COUNTRIES:
        if c.lower() in low:
            country = ALIASES.get(c, c)
            break
    return {"kind": kind, "semester": sem, "country": country, "status": status}


_LATEST = None


def latest_report_semester():
    global _LATEST
    if _LATEST is None:
        sems = []
        for d in (ROOT / "reports").iterdir():
            m = re.match(r"^(\d{4})-(spring|fall)$", d.name)
            if m and any(d.rglob("*.*")):
                sems.append((int(m[1]), m[2] == "fall", d.name))
        _LATEST = max(sems)[2] if sems else ""
    return _LATEST


def sem_key(s):
    """Chronological order: archive first, then year, spring before fall."""
    if s.startswith("archive"):
        return (0, 0)
    y = int(s[:4])
    return (y, {"spring": 1, "fall": 2}.get(s[5:], 0))


def main():
    prev = {}
    if (CAT / "CATALOG.csv").exists():
        with open(CAT / "CATALOG.csv") as fh:
            prev = {r["new_path"]: r.get("original_drive_path", "") for r in csv.DictReader(fh)}

    rows = []
    for f in sorted(ROOT.rglob("*")):
        if not f.is_file():
            continue
        rel = f.relative_to(ROOT)
        if rel.parts[0] in SKIP_TOP or rel.name in (".DS_Store", ".gitkeep") or rel.suffix == ".md" and rel.parts[0] != "reports":
            continue
        L = labels(rel)
        rows.append({"new_path": str(rel), "original_drive_path": prev.get(str(rel), ""),
                     **L, "size_bytes": f.stat().st_size})

    with open(CAT / "CATALOG.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["new_path", "original_drive_path", "kind", "semester", "country", "status", "size_bytes"])
        w.writeheader()
        w.writerows(rows)

    # --- catalog/README.md: overview + every non-bulk file listed by area
    by_kind = Counter(r["kind"] for r in rows)
    by_sem = Counter(r["semester"] for r in rows if r["semester"])
    out = ["# File Catalog", "",
           "_Auto-generated by `scripts/build_catalog.py` — do not edit by hand._", "",
           f"**{len(rows)} files.** Full machine-readable list with labels: [`CATALOG.csv`](CATALOG.csv). "
           "Country-by-semester view: [`COUNTRIES.md`](COUNTRIES.md). "
           "Readable text copies of every Word doc: [`text/`](text/).", "",
           "## Status labels", "",
           "| status | meaning |", "|---|---|",
           "| `current` | Use this. It's what the lab runs or reads today. |",
           "| `latest` | Newest finished reports. Copy their style. |",
           "| `reference` | Good to read, not part of the live pipeline. |",
           "| `archive` | Kept for history. Don't build on it. |",
           "| `do-not-use` | Known broken or superseded. |", "",
           "## Files by kind", "", "| kind | files |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in by_kind.most_common()]
    out += ["", "## Files by semester", "", "| semester | files |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in sorted(by_sem.items(), key=lambda kv: sem_key(kv[0]))]
    out += ["", "## Key files (current and latest)", ""]
    for r in rows:
        if r["status"] in ("current", "latest") and not r["new_path"].endswith((".png", ".csv", ".p", ".txt")) \
                and not r["new_path"].startswith(("data/", "presentations/archive")):
            out.append(f"- `{r['status']}` [{r['new_path']}](../{r['new_path'].replace(' ', '%20')})")
    out += ["", "## Folder notes", "",
            "- **Bulk folders are summarized, not listed:** `data/` (hundreds of CSV/XLSX/pickle files) and the "
            "per-country `output` folders under `reports/` hold chart PNGs and intermediate tables. "
            "Filter `CATALOG.csv` to browse them.",
            "- **`original_drive_path`** in `CATALOG.csv` shows where each file lived in the old Google Drive folder."]
    (CAT / "README.md").write_text("\n".join(out) + "\n")

    # --- catalog/COUNTRIES.md: which countries have reports, by semester
    grid = defaultdict(lambda: defaultdict(list))
    for r in rows:
        if r["kind"] == "country-report" and r["country"] and r["new_path"].endswith((".docx", ".pdf")):
            grid[r["country"]][r["semester"]].append(r["new_path"])
    sems = sorted({s for c in grid.values() for s in c}, key=sem_key)
    out = ["# Country Report Coverage", "",
           "_Auto-generated by `scripts/build_catalog.py`._ "
           "Each cell links to the report file(s) for that country and semester. "
           "Use this to find a country's **previous report** before updating it.", "",
           "| Country | " + " | ".join(sems) + " |", "|---|" + "---|" * len(sems)]
    for c in sorted(grid):
        cells = []
        for s in sems:
            files = grid[c].get(s, [])
            cells.append(" ".join(f"[{'pdf' if f.endswith('.pdf') else 'doc'}](../{f.replace(' ', '%20')})" for f in files[:3]))
        out.append(f"| **{c}** | " + " | ".join(cells) + " |")
    (CAT / "COUNTRIES.md").write_text("\n".join(out) + "\n")
    print(f"catalog: {len(rows)} files, {len(grid)} countries with reports")


if __name__ == "__main__":
    main()
